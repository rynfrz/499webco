  'function stopEdit(){if(!active)return;var el=active;active=null;el.removeAttribute("contenteditable");var sc=scopeOf(el);if(sc)post({type:"field",scope:sc,key:el.getAttribute("data-f"),value:{html:cleanHtml(el)},final:true});post({type:"editing",on:false});}',
  'd.addEventListener("input",function(e){var el=e.target.closest&&e.target.closest("[data-f]");if(!el||el!==active)return;var sc=scopeOf(el);if(sc)post({type:"field",scope:sc,key:el.getAttribute("data-f"),value:{html:cleanHtml(el)}});},true);',
  'd.addEventListener("keydown",function(e){if(!active)return;if(e.key==="Escape"){e.preventDefault();active.blur();stopEdit();return;}if(e.key==="Enter"){e.preventDefault();if(multiline(active)){d.execCommand("insertLineBreak");}else{active.blur();stopEdit();}}},true);',
  'd.addEventListener("paste",function(e){if(!active)return;e.preventDefault();var t=(e.clipboardData||window.clipboardData).getData("text/plain")||"";d.execCommand("insertText",false,t.replace(/\\s+/g," "));},true);',
  'd.addEventListener("focusout",function(e){if(active&&e.target===active)setTimeout(function(){if(d.activeElement!==active)stopEdit();},0);},true);',
