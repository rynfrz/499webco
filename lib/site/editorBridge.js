  ' var a=t.closest("a");',
  ' if(preview){if(a){e.preventDefault();var h=a.getAttribute("href")||"";if(h.charAt(0)==="/"||h.charAt(0)==="#")post({type:"navigate",href:h});}return;}',
  ' var f=t.closest("[data-f]");',
